type Locale = keyof typeof labels

const styles = StyleSheet.create({
  page: { fontFamily: 'Roboto', fontWeight: 'normal', fontSize: 10, padding: 40, color: '#1a1a1a' },
  header: { marginBottom: 24 },
  title: { fontSize: 18, fontWeight: 'bold', marginBottom: 4 },
  subtitle: { fontSize: 10, color: '#6b7280' },
  section: { marginBottom: 20 },
  sectionTitle: { fontSize: 12, fontWeight: 'bold', marginBottom: 8, paddingBottom: 4, borderBottomWidth: 1, borderBottomColor: '#e5e7eb' },
  row: { flexDirection: 'row', justifyContent: 'space-between', marginBottom: 5 },
  label: { color: '#6b7280' },
  value: { fontWeight: 'bold' },
  positive: { color: '#16a34a' },
  negative: { color: '#dc2626' },
  goalCard: { padding: 10, marginBottom: 8, backgroundColor: '#f9fafb', borderRadius: 4 },
  goalName: { fontSize: 11, fontWeight: 'bold', marginBottom: 6 },
  indent: { paddingLeft: 8 },
  footer: { position: 'absolute', bottom: 30, left: 40, right: 40, textAlign: 'center', color: '#9ca3af', fontSize: 8 },
})

function ProfitText({ value, formatted }: { value: number; formatted: string }) {
  return <Text style={value >= 0 ? styles.positive : styles.negative}>{formatted}</Text>
}

function LabelRow({ label, value, profitValue }: { label: string; value: string; profitValue?: number }) {
  return (
    <View style={styles.row}>
      <Text style={styles.label}>{label}</Text>
      {profitValue !== undefined
        ? <ProfitText value={profitValue} formatted={value} />
        : <Text style={styles.value}>{value}</Text>
      }
    </View>
  )
}

export function PortfolioReport({ data, locale = 'vi' }: { data: DashboardData; locale?: string }) {
  const l = labels[(locale as Locale) in labels ? (locale as Locale) : 'vi']
  const { netWorth, goals, byType } = data
  // Rendered on the server (UTC), so the zone has to be explicit or the PDF prints
  // yesterday while its own filename says today (#591).
  const generatedDate = formatBusinessDate(locale === 'vi' ? 'vi-VN' : 'en-GB', { day: '2-digit', month: '2-digit', year: 'numeric' })

  const mutualFundsTotal = [
    ...data.goals.flatMap((g) => g.funds),
    ...data.unallocated.funds,
  ].reduce((sum, f) => sum + f.currentValue, 0)

  return (
    <Document>
      <Page size="A4" style={styles.page}>
        <View style={styles.header}>
          <Text style={styles.title}>{l.title}</Text>
          <Text style={styles.subtitle}>{l.generatedOn}: {generatedDate}</Text>
        </View>

        <View style={styles.section}>
          <Text style={styles.sectionTitle}>{l.netWorthSection}</Text>
          <LabelRow label={l.totalInvested} value={fmt(netWorth.totalInvested)} />
          <LabelRow label={l.currentValue} value={fmt(netWorth.currentValue)} />
          <LabelRow
            label={l.profitLoss}
            value={`${netWorth.overallProfitLoss >= 0 ? '+' : ''}${fmt(netWorth.overallProfitLoss)} (${fmtPct(netWorth.overallProfitLossPercentage)})`}
            profitValue={netWorth.overallProfitLoss}
          />
        </View>

        <View style={styles.section}>
          <Text style={styles.sectionTitle}>{l.assetSection}</Text>
          {mutualFundsTotal > 0 && <LabelRow label={l.mutualFunds} value={fmt(mutualFundsTotal)} />}
          {byType.bank > 0 && <LabelRow label={l.bankDeposit} value={fmt(byType.bank)} />}
          {byType.gold > 0 && <LabelRow label={l.gold} value={fmt(byType.gold)} />}
          {byType.stock > 0 && <LabelRow label={l.stock} value={fmt(byType.stock)} />}
          {mutualFundsTotal === 0 && byType.bank === 0 && byType.gold === 0 && byType.stock === 0 && (
            <Text style={styles.label}>{l.noAssets}</Text>
          )}
        </View>

        {goals.length > 0 && (
          <View style={styles.section}>
            <Text style={styles.sectionTitle}>{l.goalsSection}</Text>
            {goals.map((goal) => {
              // A finished goal was liquidated, so every live figure here reads
              // zero — the export would report a goal with years of history as
              // worth 0 and 0% complete. It reads its snapshot instead (#650),
              // the same rule the cards and the detail views follow.
              const completion = goalCompletion(goal)
              return (
              <View key={goal.goalId} style={styles.goalCard}>
                <Text style={styles.goalName}>{goal.goalName}</Text>
                <View style={styles.indent}>
                  {completion ? (
                    <>
                      <LabelRow label={l.completionValue} value={fmt(completion.value)} />
                      <LabelRow
                        label={l.target}
                        value={goal.targetAmount != null
                          ? `${fmt(goal.targetAmount)} — ${l.completed} · ${completion.percentage.toFixed(0)}%`
                          : `${l.completed} · ${completion.percentage.toFixed(0)}%`}
                      />
                    </>
                  ) : (
                    <>
                      <LabelRow label={l.invested} value={fmt(goal.totalInvested)} />
                      <LabelRow label={l.currentValue} value={fmt(goal.currentValue)} />
                      <LabelRow
                        label={l.profitLoss}
                        value={`${goal.profitLoss >= 0 ? '+' : ''}${fmt(goal.profitLoss)} (${fmtPct(goal.profitLossPercentage)})`}
                        profitValue={goal.profitLoss}
                      />
                      {goal.targetAmount != null && goal.progressPercentage != null ? (
                        <LabelRow label={l.target} value={`${fmt(goal.targetAmount)} — ${goal.progressPercentage.toFixed(1)}% ${l.complete}`} />
                      ) : (
                        <LabelRow label={l.target} value={l.noTarget} />
                      )}
                    </>
                  )}
                </View>
              </View>
              )
            })}
          </View>
        )}

        <Text style={styles.footer}>{l.footer} · {generatedDate}</Text>
      </Page>
    </Document>
  )
}
